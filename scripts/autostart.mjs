// Tier 3.3: Windows per-user autostart via Task Scheduler (schtasks.exe).
// Per-user ONLOGON tasks need no admin rights, so this matches the
// "no terminal, ever" promise: the daemon is already running when he
// opens his laptop. Pure builders are exported for tests.
import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export const TASK_NAME = 'PersonalAgent';

/** The launcher lives in the repo so a `git pull` updates it in place. */
export function launcherPath(repoRoot) { return join(repoRoot, 'scripts', 'start-agent.cmd'); }

export function launcherScript() {
  return [
    '@echo off',
    'rem Auto-generated by npm run doctor --install-autostart - do not edit by hand.',
    'cd /d "%~dp0.."',
    'start "Personal Agent" /min cmd /c "npm start >> data\\agent-console.log 2>&1"',
    '',
  ].join('\r\n');
}

/** schtasks argument lists (arrays, never shell strings - no injection surface). */
export function createArgs(launcher) {
  return ['/Create', '/TN', TASK_NAME, '/SC', 'ONLOGON', '/RL', 'LIMITED', '/TR', `"${launcher}"`, '/F'];
}
export function deleteArgs() { return ['/Delete', '/TN', TASK_NAME, '/F']; }
export function queryArgs() { return ['/Query', '/TN', TASK_NAME]; }

export function isWindows() { return process.platform === 'win32'; }

export function isAutostartInstalled(exec = execFileSync) {
  if (!isWindows()) return false;
  try { exec('schtasks', queryArgs(), { stdio: 'pipe' }); return true; } catch { return false; }
}

export function installAutostart(repoRoot, exec = execFileSync) {
  if (!isWindows()) return { ok: false, detail: 'autostart is Windows-only; on other systems use your init system (systemd --user, launchd, cron @reboot)' };
  const launcher = launcherPath(repoRoot);
  writeFileSync(launcher, launcherScript());
  try {
    exec('schtasks', createArgs(launcher), { stdio: 'pipe' });
    return { ok: true, detail: `task "${TASK_NAME}" runs ${launcher} at every sign-in` };
  } catch (e) {
    return { ok: false, detail: `schtasks failed: ${e.stderr?.toString().trim() || e.message}` };
  }
}

export function removeAutostart(exec = execFileSync) {
  if (!isWindows()) return { ok: false, detail: 'autostart is Windows-only' };
  try { exec('schtasks', deleteArgs(), { stdio: 'pipe' }); return { ok: true, detail: `task "${TASK_NAME}" removed` }; }
  catch (e) { return { ok: false, detail: `schtasks failed: ${e.stderr?.toString().trim() || e.message}` }; }
}
